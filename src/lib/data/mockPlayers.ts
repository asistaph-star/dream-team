// TIER RATING SYSTEM (Based on real 2025-26 NBA Rankings)
// ═══════════════════════════════════════════════════════
// S+    = >= 98 OVR  — Generational MVP Tier
// S     = 95-97 OVR  — Superstar Elite
// S-    = 92-94 OVR  — All-NBA Star
// A+    = 89-91 OVR  — All-Star Focus
// A     = 85-88 OVR  — Elite Starter
// A-    = 80-84 OVR  — Quality Starter
// B+    = 75-79 OVR  — Solid Rotation
// B     = 70-74 OVR  — Role Player
// B-    = 65-69 OVR  — Bench Depth
// C+    = 60-64 OVR  — End of Bench
// C     = 55-59 OVR  — End of Bench Backup
// C-    = 50-54 OVR  — Reserve
// D+    = 45-49 OVR  — Prospect
// D     = 40-44 OVR  — G-League Depth
// D-    = < 40  OVR  — G-League Candidate
// ═══════════════════════════════════════════════════════

export const getTierRating = (ovr: number): string => {
  if (ovr >= 98) return 'S+';
  if (ovr >= 95) return 'S';
  if (ovr >= 92) return 'S-';
  if (ovr >= 89) return 'A+';
  if (ovr >= 85) return 'A';
  if (ovr >= 80) return 'A-';
  if (ovr >= 75) return 'B+';
  if (ovr >= 70) return 'B';
  if (ovr >= 65) return 'B-';
  if (ovr >= 60) return 'C+';
  if (ovr >= 55) return 'C';
  if (ovr >= 50) return 'C-';
  if (ovr >= 45) return 'D+';
  if (ovr >= 40) return 'D';
  return 'D-';
};

export const getTierColor = (tier: string): string => {
  if (tier === 'S+') return '#ff2d55';  // Vivid red-violet / Hot pink
  if (tier === 'S')  return '#ff6b35';  // Fire orange
  if (tier === 'S-') return '#ffd700';  // Bright gold
  if (tier === 'A+') return '#a855f7';  // Royal purple
  if (tier === 'A')  return '#6366f1';  // Indigo
  if (tier === 'A-') return '#06b6d4';  // Cyan
  if (tier === 'B+') return '#10b981';  // Emerald green
  if (tier === 'B')  return '#84cc16';  // Lime green
  if (tier === 'B-') return '#eab308';  // Soft amber
  if (tier === 'C+') return '#64748b';  // Slate blue
  if (tier === 'C')  return '#4b5563';  // Slate gray
  if (tier === 'C-') return '#374151';  // Charcoal
  if (tier === 'D+') return '#991b1b';  // Faded red
  if (tier === 'D')  return '#7f1d1d';  // Faded maroon
  return '#1f2937';                     // Dark charcoal
};

